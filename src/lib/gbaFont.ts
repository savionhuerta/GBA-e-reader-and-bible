/**
 * Generates a 256-entry * 8-byte bitmap table (2048 bytes total).
 * If wideBold is true, horizontally doubles selected edges into 7px wide glyphs for 8x8 display.
 */
export function buildGbaFontTable(wideBold = false): Uint8Array {
  const table = new Uint8Array(256 * 8);
  for (let code = 0; code < 256; code++) {
    const pattern = GLYPH_PATTERNS[code] ?? GLYPH_PATTERNS[0x20];
    for (let row = 0; row < 8; row++) {
      const line = pattern[row] ?? '.....';
      let byte = 0;
      for (let col = 0; col < 5; col++) {
        if (line[col] === '#') {
          byte |= 1 << (7 - col);
        }
      }
      if (wideBold) {
        // Stretch 5-bit pattern cleanly into 7-bit bold pattern in bits 7..1
        let wide = 0;
        if (byte & 0x80) wide |= 0x80;
        if (byte & 0x40) wide |= 0x60;
        if (byte & 0x20) wide |= 0x18;
        if (byte & 0x10) wide |= 0x04;
        if (byte & 0x08) wide |= 0x02;
        byte = wide;
      }
      table[code * 8 + row] = byte;
    }
  }
  return table;
}
