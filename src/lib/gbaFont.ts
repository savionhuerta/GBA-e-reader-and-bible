export function hexToBgr555(hex: string): number {
  const clean = hex.replace('#', '');
  const r = Math.round((parseInt(clean.slice(0, 2), 16) * 31) / 255) & 0x1f;
  const g = Math.round((parseInt(clean.slice(2, 4), 16) * 31) / 255) & 0x1f;
  const b = Math.round((parseInt(clean.slice(4, 6), 16) * 31) / 255) & 0x1f;
  return r | (g << 5) | (b << 10);
}

export function getThemeBgr555Palette(theme: GbaTheme): number[] {
  return [
    hexToBgr555(theme.colors.bg),
    hexToBgr555(theme.colors.ink),
    hexToBgr555(theme.colors.muted),
    hexToBgr555(theme.colors.verse),
    hexToBgr555(theme.colors.barBg),
    hexToBgr555(theme.colors.divider),
    hexToBgr555(theme.colors.selBg),
    hexToBgr555(theme.colors.selText),
  ];
}

